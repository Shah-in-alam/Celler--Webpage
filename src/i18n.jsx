const LanguageContext = createContext(null)

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('cellar-lang')
      if (saved === 'en' || saved === 'nl') return saved
    }
    return 'en'
  })

  useEffect(() => {
    if (typeof localStorage !== 'undefined') localStorage.setItem('cellar-lang', lang)
    document.documentElement.lang = lang
  }, [lang])

  const toggle = useCallback(() => setLang((l) => (l === 'en' ? 'nl' : 'en')), [])

  const value = { lang, setLang, toggle, t: translations[lang] }
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLang() {
  const ctx = useContext(LanguageContext)
  if (!ctx) throw new Error('useLang must be used within LanguageProvider')
  return ctx
}
